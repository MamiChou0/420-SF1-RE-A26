import math

# sum(iterable, start) fait la somme des valeurs contenues dans iterable et ajoute start (optionel) au début
print(sum([4, 5, 6, 7, 42, 9], 33))

# min(iterable) renvoie la valeur minimum dans l'itérable
print(min([89, 3, 6, -1, 5, 8]))

# max(iterable) renvoie la valeur maximum de l'itérable
print(max([2**5, 42, 55, -1]))

# round(valeur, digits) arrondi la valeur au nombre de décimales (digits)
print(round(math.pi, 5))

