# entier
x = 5
print(type(x))

# float
mon_float = 5.0
print(type(mon_float))

# nombre_complex
nombre_complex = 5+6j
print(type(nombre_complex))

# chaîne de caractères
ma_str = "Ceci est un texte"
ma_str2 = 'Ceci est un texte'
print(type(ma_str), type(ma_str2))

# Booléens
vrai = True
faux = False
print(type(vrai), type(faux))

# d'autres types existent: hex, bytes

# Le type None permet d'assigner aucune valeur
rien = None
print(type(rien))


