# Pour convertir une str ou autre type en int
ma_str = "2026"
ma_str_en_int = int(ma_str)
mon_float = 3.1416
print(int(mon_float))

# Pour convertir vers un float, on utilise float()
mon_int_en_float = float(42)
print(mon_int_en_float)

# Pour convertir en str, on utilise str()
mon_int_en_str = str(ma_str_en_int)
print(mon_int_en_str)

