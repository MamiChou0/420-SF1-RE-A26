# print() affiche à la console. print() convertit automatiquement les arguments en str
nombre = 42
pi = 3.1416
bonjour = "bonjour"
# lorsque l'on spécifie plusieurs arguments, il les affiche en les séparant d'un espace par défaut
print(nombre, pi, bonjour)
# On peut changer le séparateur
print(nombre, pi, bonjour, sep="><")

# print() ajoute automatiquement une nouvelle ligne à la fin par défaut
print(bonjour)
print(bonjour, end="")
print()
print(bonjour, end="ppppppppp")
print("salut")



